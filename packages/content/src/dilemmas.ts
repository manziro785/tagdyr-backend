const dilemmaSchema = z.object({
  code: z.string().min(1),
  prompt: z.string().min(1),
  options: z.array(z.string().min(1)).min(2).max(10),
});

/** Валидация на загрузке модуля — кривой контент падает на старте, а не в проде (§8). */
export const dilemmas: Dilemma[] = z.array(dilemmaSchema).parse(RAW);

/**
 * Дилемма на дату — детерминированно, без БД и без рандома: одна и та же
 * дата всегда даёт одну и ту же дилемму на всех инстансах.
 */
export function dilemmaForDate(isoDate: string): Dilemma {
  const daysSinceEpoch = Math.floor(Date.parse(`${isoDate}T00:00:00Z`) / 86_400_000);
  const index = ((daysSinceEpoch % dilemmas.length) + dilemmas.length) % dilemmas.length;
  return dilemmas[index]!;
}
